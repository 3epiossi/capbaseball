export type Locale = 'zh-TW' | 'ja' | 'en';
export type LocalePref = 'auto' | Locale;

const STORAGE_KEY = 'capbaseball_locale_v1';

export function resolveAutoLocale(): Locale {
  if (typeof window !== 'undefined') {
    const param = new URLSearchParams(window.location.search).get('lang');
    if (param === 'ja' || param === 'zh-TW' || param === 'en') return param;
  }
  const langs: readonly string[] =
    typeof navigator !== 'undefined'
      ? navigator.languages && navigator.languages.length > 0
        ? navigator.languages
        : navigator.language
          ? [navigator.language]
          : []
      : [];

  for (const raw of langs) {
    const l = raw.toLowerCase();
    if (l.startsWith('ja')) return 'ja';
    if (l.startsWith('zh-tw') || l.startsWith('zh-hk') || l.startsWith('zh-mo') || l.includes('hant')) {
      return 'zh-TW';
    }
    if (l.startsWith('zh')) return 'zh-TW';
  }
  return 'en';
}

export function loadLocalePref(): LocalePref {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'auto' || saved === 'zh-TW' || saved === 'ja' || saved === 'en') {
      return saved;
    }
  } catch {
    // ignore storage errors
  }
  return 'auto';
}

export function saveLocalePref(pref: LocalePref): void {
  try {
    localStorage.setItem(STORAGE_KEY, pref);
  } catch {
    // ignore storage errors
  }
}

export function getActiveLocale(pref: LocalePref): Locale {
  return pref === 'auto' ? resolveAutoLocale() : pref;
}

