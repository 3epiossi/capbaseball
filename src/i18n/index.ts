export type DictKey = keyof typeof DICT.en;

export function createTranslator(locale: Locale) {
  const table = DICT[locale];
  return (key: DictKey): string => table[key] ?? DICT.en[key];
}

export function localizeServerCallout(
  locale: Locale,
  title: string,
  subtitle: string,
): { title: string; subtitle: string } {
  if (locale === 'en') return { title, subtitle };
  const t = createTranslator(locale);
  const titleMap: Record<string, DictKey> = {
    'HOME RUN!': 'callHr',
    'TRIPLE!': 'callTriple',
    'DOUBLE!': 'callDouble',
    'SINGLE!': 'callSingle',
    FOUL: 'callFoul',
    'OUT!': 'callOut',
    STRIKE: 'callStrike',
    'STRIKE OUT!': 'callStrikeOut',
    BALL: 'callBall',
    'WALK (BB)': 'callWalk',
    'UNCAUGHT 3RD': 'callUncaught3rd',
    'WILD PITCH': 'callWildPitch',
    'TOO EARLY': 'callTooEarly',
    'TOO LATE': 'callTooLate',
    'OFF TARGET': 'callOffTarget',
    'SWINGING STRIKE': 'callSwingingStrike',
    'INNING CHANGE': 'callInningChange',
    'INTENTIONAL WALK': 'btnIbb',
  };
  const subMap: Record<string, DictKey> = {
    'CALLED STRIKE': 'callCalledStrike',
    'CALLED STRIKE THREE': 'callCalledStrike3',
    'OUTSIDE ZONE': 'callOutsideZone',
    'BASE ON BALLS': 'callBaseOnBalls',
    'DROPPED 3RD · BATTER TO 1B': 'callDropped3rd',
    'WILD PITCH · RUNNERS ADVANCE': 'callWildPitchSub',
    'FOUL BALL': 'callFoulBall',
    'OUTFIELD CATCH!': 'callCatch',
    'INFIELD OUT!': 'callInfieldOut',
    'FIELDER BOBBLE · SAFE!': 'callBobbleSafe',
    STRIKE: 'callStrike',
    'STRIKE OUT!': 'callStrikeOut',
    'SWINGING STRIKE': 'callSwingingStrike',
  };
  return {
    title: titleMap[title] ? t(titleMap[title]) : title,
    subtitle: subMap[subtitle] ? t(subMap[subtitle]) : subtitle,
  };
}
