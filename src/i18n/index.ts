export type DictKey = keyof typeof DICT.en;

export function createTranslator(locale: Locale) {
  const table = DICT[locale];
  return (key: DictKey): string => table[key] ?? DICT.en[key];
}

export function formatInningHalf(locale: Locale, half: 'top' | 'bottom', inning: number): string {
  if (locale === 'zh-TW') return `${inning}局${half === 'top' ? '上' : '下'}`;
  if (locale === 'ja') return `${inning}回${half === 'top' ? '表' : '裏'}`;
  return `${half === 'top' ? 'TOP' : 'BOT'} ${inning}`;
}

export function getPitchShortLabel(locale: Locale, codeOrId: string): string {
  const t = createTranslator(locale);
  const key = codeOrId.toUpperCase();
  if (key === 'STRAIGHT' || key === '4SFB' || key === 'STR' || key === 'FB') return t('pitchShortStraight');
  if (key === 'CUTTER' || key === 'CUT') return t('pitchShortCutter');
  if (key === 'FORK' || key === 'FRK') return t('pitchShortFork');
  if (key === 'CHANGEUP' || key === 'CH' || key === 'CHG') return t('pitchShortChangeup');
  return codeOrId;
}

export function localizeTelemetry(locale: Locale, raw: string): string {
  if (locale === 'en' || !raw) return raw;
  const t = createTranslator(locale);
  let out = raw;
  out = out.replace(/\b(4SFB|STR|CUT|FORK|FRK|CHG|CH)\b/g, (m) => getPitchShortLabel(locale, m));
  out = out.replace(/\bBRK\b/g, t('brkShort'));
  out = out.replace(/\bEV\b/g, t('evShort'));
  out = out.replace(/\bLA\b/g, t('laShort'));
  return out;
}

